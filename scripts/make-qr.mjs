// Emits the 25 print QR codes (23 chapters, home ×2) as SVG to /qr, plus print-ready PNGs
// set inside the hand-drawn frame (assets/art/emblems/qr-frame) and a contact sheet.
// Error correction M, quiet zone 4 modules. Print at ≥ 0.75 in (19 mm) with the URL in
// small type beneath (SPEC.md §6). Re-run after setting `domain` in site.config.mjs.
import QRCode from 'qrcode';
import sharp from 'sharp';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import site from '../site.config.mjs';

const root = resolve(import.meta.dirname, '..');
const out = resolve(root, 'qr');
mkdirSync(out, { recursive: true });
mkdirSync(resolve(out, 'framed'), { recursive: true });

const domain = site.domain.replace(/\/$/, '');
if (/example/.test(domain)) {
  console.warn('⚠  site.config.mjs domain is still a placeholder (' + domain + '). Codes will be regenerated when it is set.');
}

const targets = [
  { file: 'home-back-cover', url: `${domain}/`, label: 'Back cover' },
  { file: 'home-copyright-page', url: `${domain}/`, label: 'Copyright page' },
  ...Array.from({ length: 23 }, (_, i) => ({ file: `ch-${String(i + 1).padStart(2, '0')}`, url: `${domain}/ch/${i + 1}/`, label: `Chapter ${i + 1}` })),
];

// The frame: a 2048px square with an empty white window in the middle. The window was
// measured on the delivered artwork; adjust FRAME_WINDOW if the frame file changes.
const framePath = resolve(root, 'assets/art/emblems/qr-frame.webp');
const FRAME = 1600; // print master size (px); 1600 px ≈ 135 mm at 300 dpi
const FRAME_WINDOW = { left: 0.14, top: 0.14, size: 0.72 }; // measured: inner lines at 12.5% and 87.5%
const haveFrame = existsSync(framePath);

const rows = [];
for (const t of targets) {
  const svg = await QRCode.toString(t.url, { type: 'svg', errorCorrectionLevel: 'M', margin: 4, color: { dark: '#000000', light: '#ffffff' } });
  writeFileSync(resolve(out, `${t.file}.svg`), svg);
  // plain PNG at 1200 px for anyone who cannot place an SVG
  await QRCode.toFile(resolve(out, `${t.file}.png`), t.url, { errorCorrectionLevel: 'M', margin: 4, width: 1200 });
  if (haveFrame) {
    const win = Math.round(FRAME * FRAME_WINDOW.size);
    const qr = await QRCode.toBuffer(t.url, { errorCorrectionLevel: 'M', margin: 4, width: win, type: 'png' });
    const frame = await sharp(framePath).resize(FRAME, FRAME, { fit: 'contain', background: '#ffffff' }).flatten({ background: '#ffffff' }).toBuffer();
    await sharp(frame)
      .composite([{ input: qr, left: Math.round(FRAME * FRAME_WINDOW.left), top: Math.round(FRAME * FRAME_WINDOW.top) }])
      .png()
      .toFile(resolve(out, 'framed', `${t.file}.png`));
  }
  rows.push(t);
}

const sheet = `<!doctype html><meta charset="utf-8"><title>QR contact sheet — ${site.title}</title>
<style>body{font:14px/1.4 system-ui;margin:24px}h1{font-size:18px}.g{display:grid;grid-template-columns:repeat(auto-fill,minmax(180px,1fr));gap:24px}
figure{margin:0;text-align:center}img{width:19mm;height:19mm}img.f{width:30mm;height:30mm}figcaption{font-size:11px}code{font-size:10px;word-break:break-all}@media print{.g{gap:12px}}</style>
<h1>${site.title} — QR codes (${domain})</h1>
<p>Each code is an SVG in this folder (plain) and a PNG in <code>framed/</code> (inside the hand-drawn frame). Print the plain code at 19 mm (0.75 in) or larger with the URL beneath; the framed version works at 30 mm and up. Chapter paths are a print contract and never change. Scan a printed proof before the press run.</p>
<div class="g">${rows.map((r) => `<figure><img src="${r.file}.svg" alt="">${haveFrame ? `<img class="f" src="framed/${r.file}.png" alt="">` : ''}<figcaption><strong>${r.label}</strong><br><code>${r.url}</code></figcaption></figure>`).join('')}</div>`;
writeFileSync(resolve(out, 'index.html'), sheet);
writeFileSync(
  resolve(out, 'README.md'),
  `# QR codes\n\nGenerated by \`npm run qr\` from \`site.config.mjs\` (domain: ${domain}).\n\n| File | Target | Placement |\n|---|---|---|\n${rows.map((r) => `| ${r.file}.svg / .png / framed/${r.file}.png | ${r.url} | ${r.label} |`).join('\n')}\n\nPrint spec: SVG (vector) or PNG at 1200 px, error correction M, quiet zone 4 modules, ≥ 19 mm square, URL printed beneath. The framed PNGs set the code inside the hand-drawn frame at 1600 px (≈ 135 mm at 300 dpi); scale down to ≥ 30 mm. Scan a printed proof before approving the press run.\n`,
);
console.log(`✓ ${rows.length} QR codes → qr/ (${haveFrame ? 'plain + framed' : 'plain only'}; open qr/index.html for a contact sheet)`);
